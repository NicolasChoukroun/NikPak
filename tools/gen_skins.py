#!/usr/bin/env python3
"""Generate src/skins_data.rs from Nikkomander's src/skins.ts.

    python tools/gen_skins.py "D:/Claude Projects/Nikkomander/src/skins.ts"

NikPak and unNik use the same skins as Nikkomander: this copies the CSS
variables of every built-in skin (colours, gradients, radius); src/skin.rs
turns them into the window's colours and paints the backgrounds.
"""
import re
import sys
from pathlib import Path

KEEP = {
    'bg', 'bg-alt', 'panel', 'panel-alt', 'fg', 'fg-dim', 'accent', 'accent-soft', 'accent-hover', 'accent-fg',
    'cursor', 'cursor-fg', 'marked', 'dir', 'border', 'header', 'dialog', 'danger', 'ok', 'track', 'glow',
    'glow-soft', 'app-bg', 'panel-bg', 'dialog-bg', 'icon-dir', 'icon-arc', 'icon-img', 'icon-code',
    'icon-media', 'icon-file', 'radius',
}


def js_string(s, i):
    """Parse a JS string literal starting at s[i]; return (value, next index)."""
    q = s[i]
    out = []
    i += 1
    while s[i] != q:
        if s[i] == '\\':
            out.append(s[i + 1])
            i += 2
        else:
            out.append(s[i])
            i += 1
    return ''.join(out), i + 1


def main():
    src = Path(sys.argv[1] if len(sys.argv) > 1 else 'skins.ts').read_text(encoding='utf-8')
    consts = dict(re.findall(r"^\s*(\w+): '(#[0-9A-Fa-f]+)',", src[src.index('export const NIKKOID'):src.index('const K = NIKKOID')], re.M))
    body = src[src.index('export const BUILTIN_SKINS'):]
    body = body[:body.index('\n];')]
    skins = []
    for m in re.finditer(r"mk\('([^']+)', '((?:[^'\\]|\\.)*)', (true|false), \{", body):
        sid, name, dark = m.group(1), m.group(2).replace("\\'", "'"), m.group(3) == 'true'
        i = m.end()
        depth = 1
        vars_ = {}
        # walk the object literal: key: value pairs, skipping comments
        while depth:
            c = body[i]
            if body.startswith('//', i):
                i = body.index('\n', i)
                continue
            if c == '}':
                depth -= 1
                i += 1
                continue
            km = re.match(r"\s*(?:'([\w-]+)'|([A-Za-z_][\w]*))\s*:\s*", body[i:])
            if km:
                key = km.group(1) or km.group(2)
                i += km.end()
                if body[i] in "'`\"":
                    val, i = js_string(body, i)
                    val = re.sub(r'\$\{K\.(\w+)\}', lambda mm: consts[mm.group(1)], val)
                else:
                    vm = re.match(r'K\.(\w+)', body[i:])
                    val = consts[vm.group(1)]
                    i += vm.end()
                vars_[key] = val
                continue
            i += 1
        skins.append((sid, name, dark, {k: v for k, v in vars_.items() if k in KEEP}))

    def rs(s):
        return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

    lines = [
        '//! The CSS variables of all 89 skins of NikPak; src/skin.rs turns them into',
        '//! colours. The 75 skins of Nikkomander are generated by tools/gen_skins.py',
        '//! from its src/skins.ts; the 14 skins of NikPak (Moon, America, Pattaya',
        '//! Neons, Burgers Tokyo, Sushi, Amiga, MSX, Colecovision, ZX Spectrum,',
        '//! Cat Life, Dog Life, Mario Bros, Counter Strike, Chess) are written by hand',
        '//! at the end of the file and the generator keeps them when it runs again.',
        '//! Their painted backgrounds live in src/skin_scenes.rs.',
        '',
        '#[rustfmt::skip]',
        'pub(crate) const BUILTIN: &[(&str, &str, bool, &[(&str, &str)])] = &[',
    ]
    for sid, name, dark, v in skins:
        lines.append(f'    ({rs(sid)}, {rs(name)}, {str(dark).lower()}, &[')
        for k, val in v.items():
            lines.append(f'        ({rs(k)}, {rs(val)}),')
        lines.append('    ]),')
    lines.append('];')
    out = Path(__file__).resolve().parent.parent / 'src' / 'skins_data.rs'
    # the hand-written skins of NikPak live at the end of the same file: keep
    # that block when the 41 generated ones are rewritten
    marker = '// ===========================================================================\n// NikPak\'s own skins'
    tail = ''
    if out.exists():
        old = out.read_text(encoding='utf-8')
        if marker in old:
            tail = '\n\n' + old[old.index(marker):]
        else:
            print('WARNING: no NikPak skins block found in', out, '- it will be lost')
    out.write_text('\n'.join(lines) + tail + ('' if tail else '\n'), encoding='utf-8')
    print(f'{len(skins)} generated skins -> {out}')


if __name__ == '__main__':
    main()
