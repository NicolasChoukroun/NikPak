//! Translations of the graphical interface (the command line stays in English).
//!
//! The ten most spoken languages in the world (Ethnologue 2025, total speakers):
//! English, Mandarin Chinese, Hindi, Spanish, Arabic, French, Bengali,
//! Portuguese, Russian, Indonesian.
//!
//! Each table maps the English text to its translation. `t()` looks a text up
//! in the current language and falls back to English. `{}` placeholders are
//! filled in order by `tf()`.

use std::sync::atomic::{AtomicU8, Ordering};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    Zh,
    Hi,
    Es,
    Ar,
    Fr,
    Bn,
    Pt,
    Ru,
    Id,
}

/// In the order of the number of speakers (Ethnologue 2025).
pub const ALL: [Lang; 10] = [Lang::En, Lang::Zh, Lang::Hi, Lang::Es, Lang::Ar, Lang::Fr, Lang::Bn, Lang::Pt, Lang::Ru, Lang::Id];

impl Lang {
    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Zh => "zh",
            Lang::Hi => "hi",
            Lang::Es => "es",
            Lang::Ar => "ar",
            Lang::Fr => "fr",
            Lang::Bn => "bn",
            Lang::Pt => "pt",
            Lang::Ru => "ru",
            Lang::Id => "id",
        }
    }

    /// The language's own name, as shown in the language menu.
    pub fn native_name(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Zh => "中文",
            Lang::Hi => "हिन्दी",
            Lang::Es => "Español",
            Lang::Ar => "العربية",
            Lang::Fr => "Français",
            Lang::Bn => "বাংলা",
            Lang::Pt => "Português",
            Lang::Ru => "Русский",
            Lang::Id => "Bahasa Indonesia",
        }
    }

    /// "fr", "fr-FR", "fr_FR.UTF-8", "zh-Hans-CN", "in" (old code for Indonesian) ...
    pub fn from_code(code: &str) -> Option<Lang> {
        let c = code.trim().to_ascii_lowercase();
        let base = c.split(|ch: char| ch == '-' || ch == '_' || ch == '.' || ch == '@').next().unwrap_or("");
        Some(match base {
            "en" => Lang::En,
            "zh" => Lang::Zh,
            "hi" => Lang::Hi,
            "es" => Lang::Es,
            "ar" => Lang::Ar,
            "fr" => Lang::Fr,
            "bn" => Lang::Bn,
            "pt" => Lang::Pt,
            "ru" => Lang::Ru,
            "id" | "in" => Lang::Id,
            _ => return None,
        })
    }

    /// Written right to left.
    pub fn rtl(self) -> bool {
        self == Lang::Ar
    }

    fn table(self) -> &'static [(&'static str, &'static str)] {
        match self {
            Lang::En => &[],
            Lang::Zh => ZH,
            Lang::Hi => HI,
            Lang::Es => ES,
            Lang::Ar => AR,
            Lang::Fr => FR,
            Lang::Bn => BN,
            Lang::Pt => PT,
            Lang::Ru => RU,
            Lang::Id => ID,
        }
    }
}

static CURRENT: AtomicU8 = AtomicU8::new(0);

pub fn set(lang: Lang) {
    CURRENT.store(ALL.iter().position(|l| *l == lang).unwrap_or(0) as u8, Ordering::Relaxed);
}

pub fn current() -> Lang {
    ALL[CURRENT.load(Ordering::Relaxed) as usize % ALL.len()]
}

/// Translation of a fixed English text.
pub fn t(en: &'static str) -> &'static str {
    lookup(current(), en).unwrap_or(en)
}

/// Translation of a text known only at run time (for example a licence error);
/// unknown texts are returned unchanged.
pub fn t_dyn(en: &str) -> String {
    current().table().iter().find(|(k, _)| *k == en).map(|(_, v)| v.to_string()).unwrap_or_else(|| en.to_string())
}

/// Translation with its `{}` placeholders filled in order.
pub fn tf(en: &'static str, args: &[&str]) -> String {
    let mut out = String::new();
    let mut rest = t(en);
    for a in args {
        match rest.find("{}") {
            Some(i) => {
                out.push_str(&rest[..i]);
                out.push_str(a);
                rest = &rest[i + 2..];
            }
            None => break,
        }
    }
    out.push_str(rest);
    out
}

fn lookup(lang: Lang, en: &str) -> Option<&'static str> {
    lang.table().iter().find(|(k, _)| *k == en).map(|(_, v)| *v)
}

/// The language of the operating system's user interface, if it is one of the ten.
pub fn system_language() -> Option<Lang> {
    #[cfg(windows)]
    {
        #[link(name = "kernel32")]
        extern "system" {
            fn GetUserDefaultLocaleName(name: *mut u16, len: i32) -> i32;
        }
        let mut buf = [0u16; 85];
        // SAFETY: the buffer is LOCALE_NAME_MAX_LENGTH (85) wide characters.
        let n = unsafe { GetUserDefaultLocaleName(buf.as_mut_ptr(), buf.len() as i32) };
        if n > 1 {
            if let Some(l) = Lang::from_code(&String::from_utf16_lossy(&buf[..(n - 1) as usize])) {
                return Some(l);
            }
        }
    }
    for var in ["LC_ALL", "LC_MESSAGES", "LANG", "LANGUAGE"] {
        if let Ok(v) = std::env::var(var) {
            if let Some(l) = Lang::from_code(&v) {
                return Some(l);
            }
        }
    }
    None
}

