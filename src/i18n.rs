#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_language_translates_every_text() {
        for lang in ALL.iter().skip(1) {
            let table = lang.table();
            for key in KEYS {
                assert!(table.iter().any(|(k, _)| k == key), "{:?} is missing {:?}", lang, key);
            }
            for (k, v) in table {
                assert!(KEYS.contains(k), "{:?} has an unknown key {:?}", lang, k);
                assert_eq!(k.matches("{}").count(), v.matches("{}").count(), "{:?}: placeholders differ in {:?}", lang, k);
            }
            assert_eq!(table.len(), KEYS.len(), "{:?} has duplicate keys", lang);
        }
    }

    #[test]
    fn codes() {
        assert_eq!(Lang::from_code("fr_FR.UTF-8"), Some(Lang::Fr));
        assert_eq!(Lang::from_code("zh-Hans-CN"), Some(Lang::Zh));
        assert_eq!(Lang::from_code("in"), Some(Lang::Id));
        assert_eq!(Lang::from_code("de-DE"), None);
        for l in ALL {
            assert_eq!(Lang::from_code(l.code()), Some(l));
        }
    }

    #[test]
    fn placeholders() {
        set(Lang::Fr);
        assert_eq!(tf("{} of {}", &["1 MB", "2 MB"]), "1 MB sur 2 MB");
        set(Lang::En);
        assert_eq!(tf("{} (company licence, {} seats)", &["ACME", "25"]), "ACME (company licence, 25 seats)");
    }
}
